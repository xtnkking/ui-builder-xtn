#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import {
  buildPublicApiModel,
  defaultKitRoot,
  defaultSkillRoot,
} from "./public-api-model.mjs";

const toolPath = fileURLToPath(import.meta.url);
const GENERATED_NOTICE = "<!-- Generated by npm run docs:write. Do not edit directly. -->";
const CATEGORY_LABELS = {
  foundation: "Foundation",
  actions: "Actions",
  input: "Input",
  navigation: "Navigation",
  data: "Data display",
  feedback: "Feedback",
  overlay: "Overlay",
  pattern: "Page patterns",
};

function normalizeOutput(value) {
  return value.replaceAll("\r\n", "\n").replace(/[ \t]+$/gm, "").trimEnd() + "\n";
}

function markdownCell(value) {
  return String(value ?? "-").replaceAll("|", "\\|").replaceAll("\n", " ");
}

function referenceHref(reference) {
  if (reference.startsWith("references/")) return reference.slice("references/".length);
  return `../${reference}`;
}

function sourceLink(source) {
  if (!source) return "-";
  return `[${source.file}:${source.line}](../${source.file}#L${source.line})`;
}

function evidenceList(contract) {
  if (!contract) return "-";
  if (contract.mode === "none") return `none: ${contract.reason}`;
  if (contract.status !== "documented") return `${contract.mode}: ${contract.status}`;
  const refs = (contract.refs ?? []).map((reference) => `[${reference}](${referenceHref(reference)})`).join(", ");
  return `${contract.mode}: ${refs || "documented"}`;
}

function defaultsSection(exportRecord) {
  if (exportRecord.defaults.length === 0) {
    const sources = exportRecord.defaultSourceFiles.map((file) => `\`${file}\``).join(", ");
    return `No public prop initializer is declared by this export. Required props, browser behavior, or composed child defaults apply. Source ownership: ${sources || "the public implementation"}.`;
  }
  const rows = exportRecord.defaults.map((record) => (
    `| \`${record.prop}\` | \`${markdownCell(record.value)}\` | [${record.source}:${record.line}](../${record.source}#L${record.line}) |`
  ));
  return [
    "| Prop | Runtime initializer | Source |",
    "| --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function tokenSection(tokens) {
  if (tokens.status === "not-applicable") return tokens.reason;
  const files = tokens.files.map((file) => `[${file}](../assets/react-kit/${file})`).join(", ") || "-";
  const names = tokens.tokens.map((token) => `\`${token}\``).join(", ") || "No custom property is referenced by the registered family CSS.";
  return `Derived from registered family CSS (${files}).\n\n${names}`;
}

function migrationSection(migration) {
  if (migration.status === "none") return migration.reason;
  const evidence = migration.typeEvidence.length
    ? ` Type evidence: ${migration.typeEvidence.map((ref) => `[${ref}](${referenceHref(ref)})`).join(", ")}.`
    : "";
  const replacement = migration.replacement ? ` Replacement: \`${migration.replacement}\`.` : "";
  const blocks = migration.codeBlocks.length
    ? `\n\n${migration.codeBlocks.map((code) => `\`\`\`tsx\n${code}\n\`\`\``).join("\n\n")}`
    : "";
  return `[${migration.heading}](${referenceHref(migration.ref)}). ${migration.summary}${replacement}${evidence}${blocks}`;
}

function exportSection(record, familyExampleAnchor) {
  const states = record.applicableStates.map((state) => `\`${state}\``).join(", ");
  const restrictions = record.restrictions.map((item) => `- ${item}`).join("\n");
  const exampleSource = `[${record.example.ref}](${referenceHref(record.example.ref)})`;
  const explorer = `[${record.example.route}](../assets/react-kit/index.html${record.example.route})`;
  const compiledExample = `[compiled family example](#${familyExampleAnchor})`;
  return `<a id="${record.anchor}"></a>
### \`${record.name}\`

| Contract | Value |
| --- | --- |
| Family | \`${record.family}\` |
| Kind / stability | \`${record.kind}\` / \`${record.stability}\` |
| State mode | \`${record.stateMode}\` |
| Parameter type | ${record.parameterType ? `\`${markdownCell(record.parameterType)}\`` : "No public parameter"} |
| Implementation | ${sourceLink(record.source)} |
| Explorer / example | ${explorer}; ${compiledExample} (case \`${record.example.id}\`, source ${exampleSource}) |
| Keyboard | ${markdownCell(evidenceList(record.keyboard))} |
| ARIA | ${markdownCell(evidenceList(record.aria))} |

Applicable states: ${states || "none"}.

#### Public TypeScript

\`\`\`ts
${record.signature}
\`\`\`

#### Runtime Defaults

${defaultsSection(record)}

#### Semantic Tokens

${tokenSection(record.semanticTokens)}

#### Limits

${restrictions}

#### Usage Excerpt

\`\`\`tsx
${record.example.excerpt}
\`\`\`

#### Migration

${migrationSection(record.migration)}`;
}

function familyApiSection(family, exportByName) {
  const records = family.publicExports.map((name) => exportByName.get(name));
  if (records.length === 0) return "";
  const example = records[0].example;
  for (const record of records) {
    if (record.example.ref !== example.ref || record.example.id !== example.id || record.example.code !== example.code) {
      throw new Error(`Family ${family.id} does not have one deterministic compiled Explorer example`);
    }
  }
  const exampleAnchor = `family-${family.id}-compiled-example`;
  const aliases = family.aliases.length ? family.aliases.map((alias) => `\`${alias}\``).join(", ") : "none";
  return `## Family \`${family.id}\`

- Category: \`${family.category}\`
- Discovery aliases: ${aliases}
- Explorer: [\`${family.explorerRoute}\`](../assets/react-kit/index.html${family.explorerRoute})

<a id="${exampleAnchor}"></a>
### Compiled Family Example

This complete module is read from the AST-verified Explorer case and consumes the public barrel. Adjust business copy and data, not the Personal UI implementation.

\`\`\`tsx
${example.code}
\`\`\`

${records.map((record) => exportSection(record, exampleAnchor)).join("\n\n---\n\n")}`;
}

export function renderComponentApi(model) {
  const exportByName = new Map(model.exports.map((record) => [record.name, record]));
  const sections = model.families
    .map((family) => familyApiSection(family, exportByName))
    .filter(Boolean)
    .join("\n\n---\n\n");
  return normalizeOutput(`${GENERATED_NOTICE}
# Personal UI Component API

This is the generated consumer API for Personal UI ${model.version}. It is built from the TypeScript public barrel, Manifest ownership, component documentation metadata, AST-verified Explorer cases, runtime default initializers, registered CSS token sources, and machine-associated migration records. The generator does not read \`component-coverage.json\`.

- Runtime exports: ${model.runtimeExportCount}
- Type-only exports: ${model.typeOnlyExportCount}
- Manifest families: ${model.familyCount}
- Public entry point: \`${model.entryPoint}\`

Run \`npm run docs:write\` after an approved API or documentation change and \`npm run docs:check\` to detect stale output.

${sections}
`);
}

function catalogRows(families, exportByName) {
  return families.map((family) => {
    const exports = family.publicExports.length
      ? family.publicExports.map((name) => {
        const record = exportByName.get(name);
        const deprecated = record.stability === "deprecated" ? " (deprecated)" : "";
        return `[\`${name}\`](component-api.md#${record.anchor})${deprecated}`;
      }).join(", ")
      : "Foundation contract (no runtime export)";
    const aliases = family.aliases.length ? family.aliases.map((alias) => `\`${alias}\``).join(", ") : "-";
    const route = `[\`${family.explorerRoute}\`](../assets/react-kit/index.html${family.explorerRoute})`;
    const sources = family.sourceFiles.map((source) => `[\`${source}\`](../assets/react-kit/${source})`).join(", ");
    return `| \`${family.id}\` | ${exports} | ${aliases} | ${route} | ${sources} |`;
  }).join("\n");
}

export function renderComponentCatalog(model) {
  const exportByName = new Map(model.exports.map((record) => [record.name, record]));
  const categories = [...new Set(model.families.map((family) => family.category))];
  const sections = categories.map((category) => {
    const families = model.families.filter((family) => family.category === category);
    return `## ${CATEGORY_LABELS[category] ?? category}

| Family | Public exports / API | Discovery aliases | Explorer route | Source ownership |
| --- | --- | --- | --- | --- |
${catalogRows(families, exportByName)}`;
  }).join("\n\n");
  return normalizeOutput(`${GENERATED_NOTICE}
# Personal UI Component Catalog

This generated index is for discovery. Follow an export link for its Props, runtime defaults, state mode, keyboard and ARIA ownership, semantic tokens, limitations, compiled example, and migration record. Import runtime APIs only from \`src/personal-ui/index.ts\` through the installed public barrel.

- Families: ${model.familyCount}
- Runtime exports: ${model.runtimeExportCount}
- Version: \`${model.version}\`

## Choosing The Right API

- Use \`Select\` for compact fixed options, \`SearchableSelect\` for caller-supplied searchable options, \`Combobox\` or \`Autocomplete\` when typed query/value behavior is required, and \`AsyncSelect\` only for remote loading. See the [form contract](form-contract.md).
- Use \`SearchInput\` as the sole owner of search and clear adornments. Server-backed filters keep draft state and request only from the explicit query command or Enter.
- Use \`DataTable.pagination\` for the integrated rounded pager and omit it only for a genuinely unpaginated table. Sorting, pinning, visibility, request state, and stable viewport height remain typed component inputs.
- Use \`Dialog\`, \`ConfirmDialog\`, and \`Drawer\` according to the [overlay contract](overlay-contract.md); do not build a local modal or portal wrapper.
- Use page-pattern exports for complete authentication, CRUD, settings, detail, wizard, import/export, and status workflows. Their Explorer routes are the compiled composition examples.
- Review [component capability limits](component-capabilities.md) before relying on virtualized, editor, upload, drag, tree, scheduling, or infinite-loading behavior.

${sections}
`);
}

export function generateComponentDocuments(options = {}) {
  const kitRoot = path.resolve(options.kitRoot ?? defaultKitRoot);
  const skillRoot = path.resolve(options.skillRoot ?? path.resolve(kitRoot, "../.."));
  const model = options.model ?? buildPublicApiModel({ kitRoot, skillRoot });
  return {
    model,
    api: renderComponentApi(model),
    catalog: renderComponentCatalog(model),
    apiPath: path.resolve(options.apiPath ?? path.join(skillRoot, "references/component-api.md")),
    catalogPath: path.resolve(options.catalogPath ?? path.join(skillRoot, "references/component-catalog.md")),
  };
}

function firstDifference(expected, actual) {
  const expectedLines = expected.split("\n");
  const actualLines = actual.split("\n");
  const limit = Math.max(expectedLines.length, actualLines.length);
  for (let index = 0; index < limit; index += 1) {
    if (expectedLines[index] !== actualLines[index]) {
      return {
        line: index + 1,
        expected: expectedLines[index] ?? "<end of file>",
        actual: actualLines[index] ?? "<end of file>",
      };
    }
  }
  return undefined;
}

export function writeComponentDocuments(documents) {
  fs.mkdirSync(path.dirname(documents.apiPath), { recursive: true });
  fs.mkdirSync(path.dirname(documents.catalogPath), { recursive: true });
  fs.writeFileSync(documents.apiPath, documents.api, "utf8");
  fs.writeFileSync(documents.catalogPath, documents.catalog, "utf8");
}

export function checkComponentDocuments(documents) {
  const stale = [];
  for (const [label, filePath, expected] of [
    ["component API", documents.apiPath, documents.api],
    ["component catalog", documents.catalogPath, documents.catalog],
  ]) {
    if (!fs.existsSync(filePath)) {
      stale.push(`${label} is missing at ${filePath}`);
      continue;
    }
    const actual = normalizeOutput(fs.readFileSync(filePath, "utf8"));
    if (actual !== expected) {
      const difference = firstDifference(expected, actual);
      stale.push(
        `${label} is stale at line ${difference?.line ?? "unknown"}: expected `
        + `${JSON.stringify(difference?.expected)}, received ${JSON.stringify(difference?.actual)}`,
      );
    }
  }
  return stale;
}

function parseArguments(argv) {
  if (argv.length !== 1 || !["--write", "--check"].includes(argv[0])) {
    throw new Error("Usage: generate-component-docs.mjs --write | --check");
  }
  return argv[0];
}

function main() {
  const mode = parseArguments(process.argv.slice(2));
  const documents = generateComponentDocuments({ kitRoot: defaultKitRoot, skillRoot: defaultSkillRoot });
  if (mode === "--write") {
    writeComponentDocuments(documents);
    process.stdout.write(
      `Generated component API and catalog for ${documents.model.runtimeExportCount} exports `
      + `across ${documents.model.familyCount} families.\n`,
    );
    return;
  }
  const stale = checkComponentDocuments(documents);
  if (stale.length) {
    process.stderr.write(`Generated component documentation check failed:\n- ${stale.join("\n- ")}\n`);
    process.exitCode = 1;
    return;
  }
  process.stdout.write(
    `Generated component documentation is current (${documents.model.runtimeExportCount} exports, `
    + `${documents.model.familyCount} families).\n`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === toolPath) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`${error.stack ?? error.message}\n`);
    process.exitCode = 1;
  }
}
