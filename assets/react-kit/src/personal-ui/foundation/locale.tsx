export type PersonalUILocale = "zh-CN" | "en-US";
export type LocaleMessageKey = keyof typeof ZH_CN_MESSAGES;
export type LocalePluralKey = keyof typeof ZH_CN_PLURALS;

type MessageValue = string | number;
type PlaceholderNames<Value extends string> = Value extends `${string}{${infer Name}}${infer Rest}`
  ? Name | PlaceholderNames<Rest>
  : never;
type MessageValues<Key extends LocaleMessageKey> = Record<PlaceholderNames<(typeof ZH_CN_MESSAGES)[Key]>, MessageValue>;
type MessageArguments<Key extends LocaleMessageKey> = [PlaceholderNames<(typeof ZH_CN_MESSAGES)[Key]>] extends [never]
  ? []
  : [values: MessageValues<Key>];
type PluralTemplate<Key extends LocalePluralKey> = (typeof ZH_CN_PLURALS)[Key]["other"];
type PluralValues<Key extends LocalePluralKey> = Record<Exclude<PlaceholderNames<PluralTemplate<Key>>, "count">, MessageValue>;
type PluralArguments<Key extends LocalePluralKey> = [Exclude<PlaceholderNames<PluralTemplate<Key>>, "count">] extends [never]
  ? []
  : [values: PluralValues<Key>];

export interface LocaleProviderProps {
  children: ReactNode;
  locale?: PersonalUILocale;
  timeZone?: string;
}

export interface PersonalUILocaleContext {
  locale: PersonalUILocale;
  timeZone?: string;
  message<Key extends LocaleMessageKey>(key: Key, ...args: MessageArguments<Key>): string;
  plural<Key extends LocalePluralKey>(key: Key, count: number, ...args: PluralArguments<Key>): string;
  formatDate(value: Date | number, options?: Intl.DateTimeFormatOptions): string;
  formatNumber(value: number, options?: Intl.NumberFormatOptions): string;
}

const DEFAULT_LOCALE: PersonalUILocale = "zh-CN";

export function assertPersonalUILocale(value: unknown, owner: string): PersonalUILocale {
  if (value !== "zh-CN" && value !== "en-US") {
    throw new RangeError(`${owner} locale must be "zh-CN" or "en-US".`);
  }
  return value;
}

export function assertPersonalUITimeZone(value: unknown, owner: string): string {
  if (typeof value !== "string" || value.trim() === "") {
    throw new RangeError(`${owner} timeZone must be a non-empty time zone accepted by Intl.DateTimeFormat.`);
  }
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: value });
  } catch {
    throw new RangeError(`${owner} timeZone must be a non-empty time zone accepted by Intl.DateTimeFormat.`);
  }
  return value;
}

function formatTemplate(
  template: string,
  values: Readonly<Record<string, MessageValue>>,
  numberFormatter: Intl.NumberFormat,
): string {
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_match, name: string) => {
    if (!(name in values)) {
      throw new Error(`Personal UI locale message is missing the "${name}" placeholder value.`);
    }
    const value = values[name];
    return typeof value === "number" ? numberFormatter.format(value) : value;
  });
}

const DEFAULT_CONTEXT: PersonalUILocaleContext = createLocaleContextValue(DEFAULT_LOCALE);
const LocaleContext = createContext<PersonalUILocaleContext>(DEFAULT_CONTEXT);

function createLocaleContextValue(locale: PersonalUILocale, timeZone?: string): PersonalUILocaleContext {
  const messages = locale === "en-US" ? EN_US_MESSAGES : ZH_CN_MESSAGES;
  const plurals = locale === "en-US" ? EN_US_PLURALS : ZH_CN_PLURALS;
  const numberFormatter = new Intl.NumberFormat(locale);
  const pluralRules = new Intl.PluralRules(locale);
  return {
    locale,
    timeZone,
    message: ((key: LocaleMessageKey, values: Record<string, MessageValue> = {}) => (
      formatTemplate(messages[key], values, numberFormatter)
    )) as PersonalUILocaleContext["message"],
    plural: ((key: LocalePluralKey, count: number, values: Record<string, MessageValue> = {}) => {
      const forms = plurals[key];
      const category = pluralRules.select(count);
      const template = "one" in forms && category === "one" ? forms.one : forms.other;
      return formatTemplate(template, { ...values, count }, numberFormatter);
    }) as PersonalUILocaleContext["plural"],
    formatDate: (value, options = {}) => new Intl.DateTimeFormat(locale, {
      ...(timeZone && options.timeZone === undefined ? { timeZone } : {}),
      ...options,
    }).format(value),
    formatNumber: (value, options) => new Intl.NumberFormat(locale, options).format(value),
  };
}

export function LocaleProvider({ children, locale, timeZone }: LocaleProviderProps) {
  const parent = useContext(LocaleContext);
  const resolvedLocale = locale === undefined
    ? parent.locale
    : assertPersonalUILocale(locale, "LocaleProvider");
  const resolvedTimeZone = timeZone === undefined
    ? parent.timeZone
    : assertPersonalUITimeZone(timeZone, "LocaleProvider");
  const value = useMemo(
    () => createLocaleContextValue(resolvedLocale, resolvedTimeZone),
    [resolvedLocale, resolvedTimeZone],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function usePersonalUILocale(): PersonalUILocaleContext {
  return useContext(LocaleContext);
}

